// Public pages and offline storage only. No real account or personal journal is changed.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const catalog = require('../data/summits.json')
const base = process.env.CHECK_URL || 'http://127.0.0.1:3000'
const output = path.join(__dirname, '../.next/improvements-check')

async function main() {
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 900 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => localStorage.setItem('100cimscat-language', 'es'))
    await page.route('https://*.supabase.co/**', route => route.fulfill({ json: route.request().url().includes('/rest/v1/summits') ? catalog : { user: null } }))
    await page.goto(base)
    await page.getByRole('searchbox').waitFor()
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.locator('.card').count(), 48)
    const fonts = await page.evaluate(() => [...document.fonts].filter(font => font.status === 'loaded').map(font => font.family))
    assert.ok(fonts.some(font => /Hanken.Grotesk/i.test(font)), JSON.stringify(fonts))
    assert.ok(fonts.some(font => /Fraunces/i.test(font)), JSON.stringify(fonts))
    const cta = page.getByRole('link', { name: /Explorar las cimas/ })
    assert.ok((await cta.boundingBox()).y < 600, 'Explore action is not near the top on mobile')
    await page.screenshot({ path: path.join(output, 'home-390.png') })
    await page.getByRole('button', { name: 'Cargar más cimas', exact: true }).click()
    assert.equal(await page.locator('.card').count(), 96)
    const link = page.locator('.card').nth(70).getByRole('link', { name: 'Explorar cima ↗' })
    await link.scrollIntoViewIfNeeded()
    await page.waitForTimeout(200)
    const previousScroll = await page.evaluate(() => scrollY)
    const summitPath = await link.getAttribute('href')
    await link.click()
    await page.getByRole('heading', { level: 1 }).waitFor()
    const raw = await page.request.get(base + summitPath)
    assert.equal(raw.status(), 200)
    const html = await raw.text()
    assert.ok(html.includes('<h1>') && html.includes('rel="canonical"') && html.includes(summitPath))
    await page.waitForFunction(summitPath => document.querySelector('link[rel="canonical"]')?.getAttribute('href') === 'https://100-cims-cat.vercel.app' + summitPath, summitPath)
    assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://100-cims-cat.vercel.app' + summitPath)
    await page.goBack()
    await page.waitForFunction(() => document.querySelectorAll('.card').length === 96)
    await page.waitForFunction(previous => Math.abs(scrollY - previous) < 100, previousScroll)
    await page.getByRole('searchbox').fill('canigo')
    await page.getByRole('heading', { level: 3, name: 'Canigó' }).waitFor()
    assert.equal(await page.locator('.card').count(), 1)
    await page.reload()
    await page.waitForFunction(() => document.querySelector('input[type="search"]')?.value.toLowerCase() === 'canigo')
    await page.getByRole('button', { name: 'Mapa', exact: true }).click()
    await page.locator('.leaflet-container').waitFor()
    await page.getByRole('button', { name: 'Acercar', exact: true }).click()
    await page.waitForTimeout(300)
    await page.getByRole('button', { name: 'Acercar', exact: true }).click()
    await page.waitForTimeout(300)
    const mapState = await page.evaluate(() => JSON.parse(sessionStorage.getItem('100cimscat-map-v1')))
    assert.ok(mapState.zoom >= 9)
    await page.reload()
    await page.locator('.leaflet-container').waitFor()
    await page.getByRole('button', { name: 'Alejar', exact: true }).click()
    await page.waitForFunction(zoom => JSON.parse(sessionStorage.getItem('100cimscat-map-v1')).zoom === zoom - 1, mapState.zoom)
    await page.goto(base + '/cims/canigo')
    await page.getByRole('heading', { level: 1, name: 'Canigó' }).waitFor()
    await page.getByRole('button', { name: /Guardar sin cobertura/ }).click()
    await page.getByRole('status').filter({ hasText: 'Ficha guardada' }).waitFor()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('100cimscat-offline-v1')))
    assert.equal(saved[0].id, 'canigo')
    assert.ok(saved[0].coordinate?.lat)
    assert.ok(!JSON.stringify(saved).includes('photo_path') && !JSON.stringify(saved).includes('notes'))
    const cached = await page.evaluate(async () => { const cache = await caches.open('100cimscat-offline-v1'); return (await cache.keys()).map(request => new URL(request.url).pathname).sort() })
    assert.deepEqual(cached, ['/icon.svg', '/offline.html', '/offline.js'])
    await page.screenshot({ path: path.join(output, 'summit-390.png') })
    await context.setOffline(true)
    await page.goto(base + '/cims/canigo')
    await page.locator('#summits h2').filter({ hasText: 'Canigó' }).waitFor()
    assert.ok((await page.locator('#summits').innerText()).includes('Coordenadas'))
    await page.reload()
    await page.locator('#summits h2').filter({ hasText: 'Canigó' }).waitFor()
    await page.screenshot({ path: path.join(output, 'offline-390.png') })
    await page.goto(base + '/cims/balandrau')
    await page.getByRole('status').filter({ hasText: 'Esta cima no está descargada.' }).waitFor()
    await page.goto(base + '/offline.html')
    await page.getByRole('button', { name: 'Quitar descarga' }).click()
    assert.equal(await page.locator('#summits article').count(), 0)
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('100cimscat-offline-v1'))), [])
    await context.setOffline(false)
    const notFound = await page.request.get(base + '/cims/unknown-summit')
    assert.equal(notFound.status(), 404)
    const sitemap = await page.request.get(base + '/sitemap.xml')
    assert.equal((await sitemap.text()).match(/<loc>/g).length, 523)
    assert.deepEqual(errors, [])
    const report = { fontFilesLoaded: fonts, initialCards: 48, expandedCards: 96, sharedSummitPages: true, serverRenderedMetadata: true, restoredFiltersScrollAndMap: true, offlineSavedReadReloadAndRemove: true, unsavedOfflineSummitExplained: true, noPrivateDataCached: true, sitemapPages: 523, errors }
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report))
    await context.close()
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
